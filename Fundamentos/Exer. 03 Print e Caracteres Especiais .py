# Exercicio 03 - Caracteres Especiais
#Os caracteres especiais são utilizados para representar caracteres que não podem ser digitados diretamente no código, como por exemplo, o caractere de nova linha (\n), o caractere de tabulação (\t), o caractere de barra invertida (\\), o caractere de aspas duplas (\") e o caractere de aspas simples (\').

# O \n é utilizado para pular uma linha.
print("olá, mundo!\nMeu nome é Jônatas Nunes\nMoro na Noruega")

# O \t é utilizado para dar um espaço de tabulação.(horizontal)
print("olá, mundo!\tMeu nome é Jônatas Nunes\tMoro na Noruega")

# O \\ é utilizado para representar a barra invertida.
print("olá, mundo!\\Meu nome é Jônatas Nunes\\Moro na Noruega")

# O \" é utilizado para representar aspas duplas.
print("olá, mundo!\"Meu nome é Jônatas Nunes\"Moro na Noruega")

# O \' é utilizado para representar aspas simples.
print("olá, mundo!\'Meu nome é Jônatas Nunes\'Moro na Noruega")

# aqui tentei implementar todos os caracteres especiais em uma única linha, junto com o parametro sep e end.,


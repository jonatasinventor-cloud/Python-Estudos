#Exercicio 04 - Strings de Múltiplas linhas

# As strings de múltiplas linhas são utilizadas para representar textos que ocupam mais de uma linha, como por exemplo, um parágrafo ou um poema.
#Elas são delimitadas por três aspas simples ou três aspas duplas. 
# As strings de múltiplas linhas podem conter quebras de linha, tabulações e outros caracteres especiais, assim como as strings de uma única linha.

# Aqui criamos também a primeira variavel chamada mensagem, que recebe uma string de múltiplas linhas, e depois utilizamos a função print() para exibir o conteúdo da variável mensagem na tela.

mensagem = """Olá, mundo!
Meu nome é Jônatas Nunes
Moro na Noruega
Estou aprendendo Python e estou testando a função print()"""

print(mensagem)
